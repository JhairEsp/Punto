create extension if not exists citext;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  username citext not null unique,
  password_hash text not null,
  position text not null,
  role text not null default 'employee' check (role in ('superadmin', 'employee')),
  active boolean not null default true,
  avatar_color text not null default '#D9F99D',
  scheduled_entry time not null default '08:00',
  scheduled_exit time not null default '17:00',
  weekly_schedule jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  type text not null check (type in ('entry', 'exit')),
  photo text not null,
  latitude double precision not null,
  longitude double precision not null,
  accuracy double precision,
  created_at timestamptz not null default now(),
  scheduled_entry time,
  scheduled_exit time,
  late_minutes integer not null default 0 check (late_minutes >= 0),
  overtime_minutes integer not null default 0 check (overtime_minutes >= 0),
  early_leave_minutes integer not null default 0 check (early_leave_minutes >= 0)
);

create index if not exists attendance_user_id_id_idx on public.attendance(user_id, id desc);
create index if not exists attendance_created_at_idx on public.attendance(created_at);
create index if not exists attendance_user_date_idx on public.attendance(user_id, created_at);

create or replace view public.user_attendance_summary as
select
  u.id, u.name, u.username, u.position, u.role, u.active, u.avatar_color,
  u.scheduled_entry, u.scheduled_exit, u.created_at,
  (select a.type from public.attendance a where a.user_id = u.id order by a.id desc limit 1) as last_type,
  (select a.created_at from public.attendance a where a.user_id = u.id order by a.id desc limit 1) as last_attendance,
  (select count(*) from public.attendance a where a.user_id = u.id) as attendance_count,
  u.weekly_schedule
from public.users u;

-- La API usa exclusivamente SERVICE_ROLE. El frontend nunca recibe esa clave.
-- RLS sin políticas públicas: anon/authenticated no tienen acceso directo a las tablas.
alter table public.users enable row level security;
alter table public.attendance enable row level security;
revoke all on table public.users from anon, authenticated;
revoke all on table public.attendance from anon, authenticated;
revoke all on table public.user_attendance_summary from anon, authenticated;
grant all on table public.users to service_role;
grant all on table public.attendance to service_role;
grant all on table public.user_attendance_summary to service_role;
grant all on all sequences in schema public to service_role;

